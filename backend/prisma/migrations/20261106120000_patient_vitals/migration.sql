CREATE TABLE `PatientVital` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `branchId` INTEGER NOT NULL,
    `patientId` INTEGER NOT NULL,
    `nurseId` INTEGER NULL,
    `admissionId` INTEGER NULL,
    `recordedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `temperature` DECIMAL(5, 2) NULL,
    `pulse` INTEGER NULL,
    `systolic` INTEGER NULL,
    `diastolic` INTEGER NULL,
    `respiratoryRate` INTEGER NULL,
    `spo2` INTEGER NULL,
    `bloodSugar` DECIMAL(6, 2) NULL,
    `weight` DECIMAL(6, 2) NULL,
    `notes` VARCHAR(500) NULL,
    `createdByUserId` INTEGER NULL,
    `deletedAt` DATETIME(3) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    PRIMARY KEY (`id`),
    INDEX `PatientVital_branchId_patientId_deletedAt_idx`(`branchId`, `patientId`, `deletedAt`),
    INDEX `PatientVital_recordedAt_idx`(`recordedAt`),
    INDEX `PatientVital_nurseId_idx`(`nurseId`),
    INDEX `PatientVital_admissionId_idx`(`admissionId`),
    INDEX `PatientVital_createdByUserId_idx`(`createdByUserId`),
    CONSTRAINT `PatientVital_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `Branch`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `PatientVital_patientId_fkey` FOREIGN KEY (`patientId`) REFERENCES `Patient`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `PatientVital_nurseId_fkey` FOREIGN KEY (`nurseId`) REFERENCES `Nurse`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `PatientVital_admissionId_fkey` FOREIGN KEY (`admissionId`) REFERENCES `Admission`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `PatientVital_createdByUserId_fkey` FOREIGN KEY (`createdByUserId`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
