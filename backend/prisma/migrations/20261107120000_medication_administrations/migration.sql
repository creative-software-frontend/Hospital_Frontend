CREATE TABLE `MedicationAdministration` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `branchId` INTEGER NOT NULL,
    `patientId` INTEGER NOT NULL,
    `prescriptionItemId` INTEGER NULL,
    `medicineId` INTEGER NULL,
    `nurseId` INTEGER NULL,
    `admissionId` INTEGER NULL,
    `medicineName` VARCHAR(191) NOT NULL,
    `dosage` VARCHAR(191) NULL,
    `route` VARCHAR(191) NULL,
    `administeredAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `status` ENUM('GIVEN', 'HELD', 'REFUSED', 'MISSED') NOT NULL DEFAULT 'GIVEN',
    `notes` VARCHAR(500) NULL,
    `createdByUserId` INTEGER NULL,
    `deletedAt` DATETIME(3) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    PRIMARY KEY (`id`),
    INDEX `MedicationAdministration_branchId_patientId_deletedAt_idx`(`branchId`, `patientId`, `deletedAt`),
    INDEX `MedicationAdministration_administeredAt_idx`(`administeredAt`),
    INDEX `MedicationAdministration_nurseId_idx`(`nurseId`),
    INDEX `MedicationAdministration_prescriptionItemId_idx`(`prescriptionItemId`),
    INDEX `MedicationAdministration_medicineId_idx`(`medicineId`),
    INDEX `MedicationAdministration_admissionId_idx`(`admissionId`),
    INDEX `MedicationAdministration_createdByUserId_idx`(`createdByUserId`),
    CONSTRAINT `MedicationAdministration_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `Branch`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_patientId_fkey` FOREIGN KEY (`patientId`) REFERENCES `Patient`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_prescriptionItemId_fkey` FOREIGN KEY (`prescriptionItemId`) REFERENCES `PrescriptionItem`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_medicineId_fkey` FOREIGN KEY (`medicineId`) REFERENCES `Medicine`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_nurseId_fkey` FOREIGN KEY (`nurseId`) REFERENCES `Nurse`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_admissionId_fkey` FOREIGN KEY (`admissionId`) REFERENCES `Admission`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT `MedicationAdministration_createdByUserId_fkey` FOREIGN KEY (`createdByUserId`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
