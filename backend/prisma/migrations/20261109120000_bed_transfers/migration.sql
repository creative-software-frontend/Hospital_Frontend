CREATE TABLE `BedTransfer` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `branchId` INTEGER NOT NULL,
    `patientId` INTEGER NOT NULL,
    `admissionId` INTEGER NOT NULL,
    `fromBedId` INTEGER NOT NULL,
    `toBedId` INTEGER NOT NULL,
    `transferDate` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `reason` VARCHAR(500) NULL,
    `notes` VARCHAR(500) NULL,
    `createdByUserId` INTEGER NULL,
    `deletedAt` DATETIME(3) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    PRIMARY KEY (`id`),
    INDEX `BedTransfer_branchId_idx`(`branchId`),
    INDEX `BedTransfer_patientId_idx`(`patientId`),
    INDEX `BedTransfer_admissionId_idx`(`admissionId`),
    INDEX `BedTransfer_fromBedId_idx`(`fromBedId`),
    INDEX `BedTransfer_toBedId_idx`(`toBedId`),
    INDEX `BedTransfer_transferDate_idx`(`transferDate`),
    INDEX `BedTransfer_deletedAt_idx`(`deletedAt`),
    CONSTRAINT `BedTransfer_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `Branch`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `BedTransfer_patientId_fkey` FOREIGN KEY (`patientId`) REFERENCES `Patient`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `BedTransfer_admissionId_fkey` FOREIGN KEY (`admissionId`) REFERENCES `Admission`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `BedTransfer_fromBedId_fkey` FOREIGN KEY (`fromBedId`) REFERENCES `Bed`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `BedTransfer_toBedId_fkey` FOREIGN KEY (`toBedId`) REFERENCES `Bed`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT `BedTransfer_createdByUserId_fkey` FOREIGN KEY (`createdByUserId`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
